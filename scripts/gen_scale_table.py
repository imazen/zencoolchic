"""Regenerate src/scale_table.rs from upstream Cool-chic's mu_scale.npy.

Usage: python -I scripts/gen_scale_table.py <Cool-Chic checkout>

The mu half of the table is exactly -64 + i/256 (checked here) and is computed in Rust.
The scale half cannot be recomputed bit-exactly (23 of 2561 entries differ from
f32(exp(f64))), so it is embedded.
"""
import sys
import numpy as np

root = sys.argv[1]
t = np.load(f"{root}/coolchic/bitstream/component/mu_scale.npy").astype(np.float32)
mu, sc = t[:32768], t[32768:]
assert np.array_equal(mu.view(np.uint32), (-64.0 + np.arange(32768) / 256.0).astype(np.float32).view(np.uint32))
lines = ["    " + ", ".join(f"0x{v:08x}" for v in sc.view(np.uint32)[k:k + 8]) + "," for k in range(0, len(sc), 8)]
src = (
    "//! Laplace scale table of Cool-chic's range coder: `scale[i]` for log-scale\n"
    "//! `-5 + i/256`, i in 0..=2560, as f32 bit patterns.\n"
    "//!\n"
    "//! Generated by `scripts/gen_scale_table.py` from upstream `coolchic/bitstream/component/mu_scale.npy`\n"
    "//! (Cool-chic a6fe38a). The values must match upstream bit for bit: the range coder's\n"
    "//! cumulative function is computed from them.\n\n"
    f"pub(crate) const N_SCALE: usize = {len(sc)};\n\n"
    "#[rustfmt::skip]\n"
    "pub(crate) const SCALE_BITS: [u32; N_SCALE] = [\n" + "\n".join(lines) + "\n];\n"
)
open("src/scale_table.rs", "w").write(src)
